"""Ports used by Luna's robot runtime; adapters own HTTP and SDK details.

Joint and gripper positions are radians, poses/metres use the world frame.
Snapshots carry generation/session/model identity. Commands require the expected
generation; uncertain writes are resolved by their original request identity.
Only measured RGBD/feedback enter observations. Viewer assets are display-only.
"""
from typing import Protocol


class RobotGeometry(Protocol):
    def query(self, arms: dict, *, links=None, views=None) -> dict: ...


class RobotGateway(Protocol):
    endpoint: str

    def start(self) -> None: ...
    def close(self) -> None: ...
    def refresh(self) -> dict: ...
    def robot_snapshot(self, *, include_tcp=False) -> dict: ...
    def prepare_observation(self, *, cancelled, progress_records) -> dict: ...
    def check_generation(self, generation: int) -> dict: ...
    def wait_for_gripper_feedback(self, arms, generation, *, timeout=3.) -> dict: ...
    def capture_rgbd(self, camera_ids=None) -> dict: ...
    def preview_rgb(self) -> dict: ...
    def viewer_manifest(self) -> dict: ...
    def viewer_scene(self) -> dict: ...
    def viewer_configuration(self, joints_deg: dict, grippers: dict) -> dict: ...
    def viewer_asset(self, path: str) -> tuple[bytes, str]: ...
    def begin_motion(self, kind, generation, sample_dt_s=.02, mode='position', arms=None, *, request_id=None) -> dict: ...
    def end_motion(self, reason='completed', *, expected_id=None, expected_request=None) -> dict: ...
    def stop(self, reason='cancelled') -> dict: ...
    def execute_trajectory_program(self, paths, grippers, dt, generation, *,
            times_s=None, tolerance_deg=1., arrival_timeout_s=30.) -> dict: ...
    def set_gripper(self, arm, closed, generation, *, arrival_timeout_s=10.) -> dict: ...
    def dwell(self, duration_s, generation) -> dict: ...
    def execute_vla(self, prompt, completion, generation) -> dict: ...
